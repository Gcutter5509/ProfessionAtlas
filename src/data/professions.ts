export const SPHERES = Array.from(new Set(PROFESSIONS.map((p) => p.sphere))) as Sphere[];

export function getProfession(slug: string): Profession | undefined {
  return PROFESSIONS.find((p) => p.slug === slug);
}

export function formatStudy(years: number): string {
  if (years === 0) return "курсы / без обязательного образования";
  const word = years === 1 ? "год" : years < 5 ? "года" : "лет";
  return `${years} ${word}`;
}
