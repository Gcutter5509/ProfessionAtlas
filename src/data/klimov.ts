/** Подбор профессий: ведущий тип профессии весит вдвое больше дополнительного */
export function matchByKlimov(scores: Record<KlimovType, number>, limit = 8): { p: Profession; match: number }[] {
  return PROFESSIONS.flatMap((p) => {
    const types = PROFESSION_KLIMOV[p.slug];
    if (!types?.length) return [];
    const weights = types.map((_, i) => (i === 0 ? 2 : 1));
    const total = weights.reduce((a, b) => a + b, 0);
    const raw = types.reduce((acc, t, i) => acc + scores[t] * weights[i], 0);
    return [{ p, match: Math.round((raw / (total * KLIMOV_MAX)) * 100) }];
  })
    .sort((a, b) => b.match - a.match)
    .slice(0, limit);
}
