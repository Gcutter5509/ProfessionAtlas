/** Ответ на пару: 0 — «А», 1 — «Б» */
export function klimovScores(answers: number[]): Record<KlimovType, number> {
  const scores = { N: 0, T: 0, H: 0, S: 0, A: 0 } as Record<KlimovType, number>;
  answers.forEach((ans, i) => {
    const pair = KLIMOV_KEY[i];
    if (pair && (ans === 0 || ans === 1)) scores[pair[ans]] += 1;
  });
  return scores;
}

/** Вывод по правилам методики */
export function klimovVerdict(scores: Record<KlimovType, number>): string {
  const sorted = KLIMOV_KEYS.map((t) => [t, scores[t]] as const).sort((a, b) => b[1] - a[1]);
  const top = sorted[0][1];
  const leaders = sorted.filter(([, s]) => s === top).map(([t]) => KLIMOV_TYPES[t].name);
  const middle = sorted.filter(([, s]) => s >= 4 && s <= 5).length;

  if (top >= 6 && leaders.length > 1)
    return `У тебя одинаково высокие баллы сразу в нескольких типах (${leaders.join(", ")}) — интересы ярко выражены во всех этих областях.`;
  if (top <= 5 && middle >= 3)
    return "Баллы распределены довольно ровно: интересы у тебя широкие и пока не ярко выражены. Это нормально — попробуй разные занятия, чтобы понять, что нравится больше.";
  return `Ярче всего выражен интерес к типу «${leaders[0]}».`;
}

